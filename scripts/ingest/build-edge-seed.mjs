// Regenerates supabase/functions/ingest/seed.ts from supabase/seed/*.json
// (the Edge Function cannot read repo files at runtime). Run: node scripts/ingest/build-edge-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
const diseases = JSON.parse(readFileSync("supabase/seed/diseases.json", "utf8"));
const orgs = JSON.parse(readFileSync("supabase/seed/organizations.json", "utf8"));
const out = `// GENERATED by scripts/ingest/build-edge-seed.mjs from supabase/seed/*.json. Do not edit by hand.
import type { SeedDisease, SeedOrganization } from "./types.ts";

export const DISEASES: SeedDisease[] = [
${diseases.map((d) => "  " + JSON.stringify(d)).join(",\n")},
];

export const ORGANIZATIONS: SeedOrganization[] = [
${orgs.map((o) => "  " + JSON.stringify(o)).join(",\n")},
];
`;
writeFileSync("supabase/functions/ingest/seed.ts", out);
console.log(`seed.ts: ${diseases.length} diseases, ${orgs.length} organizations`);
